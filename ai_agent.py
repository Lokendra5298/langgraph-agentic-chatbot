# ai_agent.py

# Step 1: Load environment variables
import os
from dotenv import load_dotenv

load_dotenv()

# Step 2: Import required libraries
from langchain_groq import ChatGroq
from langchain_tavily import TavilySearch
from langchain.agents import create_agent


# Step 3: Configure API keys
GROQ_API_KEY = os.getenv("GROQ_API_KEY")
TAVILY_API_KEY = os.getenv("TAVILY_API_KEY")


# Step 4: Define default system prompt
system_prompt = (
    "Act as an AI chatbot who is smart, friendly, "
    "helpful, and provides accurate information.")


# Step 5: Create AI Agent
def get_response_from_ai_agent(llm_id,query,allow_search=False,system_prompt=system_prompt):
    """
    Create an AI agent using Groq LLM and
    optionally enable Tavily web search.

    Args:
        llm_id (str): Groq model name.
        query (str): User question.
        allow_search (bool): Enable/disable web search.
        system_prompt (str): Instructions for the agent.

    Returns:
        str: Final response generated by the AI agent.
    """

    # Validate user input
    if not isinstance(query, str) or not query.strip():
        raise ValueError("Query must be a non-empty string.")

    # Validate Groq API key
    if not GROQ_API_KEY:
        raise ValueError(
            "GROQ_API_KEY is missing. "
            "Please configure it in your .env file."
        )

    # Initialize Groq LLM
    llm = ChatGroq(model=llm_id,api_key=GROQ_API_KEY,temperature=0)

    # Configure available tools
    tools = []

    if allow_search:

        if not TAVILY_API_KEY:
            raise ValueError(
                "TAVILY_API_KEY is missing. "
                "Please configure it in your .env file.")

        search_tool = TavilySearch(max_results=2)
        tools.append(search_tool)

    # Create AI agent
    agent = create_agent(model=llm,tools=tools,system_prompt=system_prompt)

    # Prepare user message
    state = {
        "messages": [
            {
                "role": "user",
                "content": query
            }
        ]
    }

    # Invoke agent
    response = agent.invoke(state)
    # Extract final AI response
    messages = response["messages"]
    final_response = messages[-1].content

    return final_response


# Step 6: Test AI Agent
if __name__ == "__main__":

    llm_id = "openai/gpt-oss-120b"
    query = "Explain artificial intelligence in simple words."
    response = get_response_from_ai_agent(llm_id=llm_id,query=query,allow_search=True,system_prompt=system_prompt)

    print("\nAI Agent Response:\n")
    print(response)